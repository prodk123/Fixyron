import uuid
from sqlalchemy import Column, String, Integer, Float, DateTime, Text, JSON, ForeignKey
from sqlalchemy.sql import func
from app.db.base import Base

class Repair(Base):
    __tablename__ = "repairs"

    id = Column(String, primary_key=True, default=lambda: str(uuid.uuid4()))
    analysis_id = Column(String, ForeignKey("repository_analyses.id"), nullable=False)
    reproduction_id = Column(String, ForeignKey("reproduction_attempts.id"), nullable=False)
    diagnosis_id = Column(String, ForeignKey("diagnoses.id"), nullable=False)

    # pending, generating, validating, rejected, applied, tested, failed, error
    status = Column(String, default="pending", nullable=False)
    
    summary = Column(Text, nullable=True)
    confidence = Column(Float, nullable=True)
    
    files_changed = Column(Integer, nullable=True, default=0) 
    lines_added = Column(Integer, nullable=True, default=0) 
    lines_removed = Column(Integer, nullable=True, default=0) 

    # We store the raw patch/unified diff
    patch = Column(JSON, nullable=True)
    
    # Store validation information, safety limit checks, actual diff generated by git
    patch_metadata = Column(JSON, nullable=True)
    
    # Store results from the test suite execution inside the repair workspace
    test_result = Column(JSON, nullable=True)
    
    # UUID of the temporary repair workspace
    workspace_id = Column(String, nullable=True)

    error_message = Column(Text, nullable=True)
    
    created_at = Column(DateTime(timezone=True), server_default=func.now())
    completed_at = Column(DateTime(timezone=True), nullable=True)

    # --- Week 5 Extensions ---
    max_attempts = Column(Integer, default=3, nullable=False)
    current_attempt = Column(Integer, default=0, nullable=False)
    final_status = Column(String, nullable=True)
    verification_status = Column(String, nullable=True)


class RepairAttempt(Base):
    __tablename__ = "repair_attempts"

    id = Column(String, primary_key=True, default=lambda: str(uuid.uuid4()))
    repair_id = Column(String, ForeignKey("repairs.id"), nullable=False)
    attempt_number = Column(Integer, nullable=False)

    strategy = Column(JSON, nullable=True)
    patch = Column(JSON, nullable=True)
    patch_metadata = Column(JSON, nullable=True)
    validation_result = Column(JSON, nullable=True)
    
    workspace_id = Column(String, nullable=True)
    reproduction_result = Column(JSON, nullable=True)
    regression_result = Column(JSON, nullable=True)
    
    review = Column(JSON, nullable=True)
    failure_category = Column(String, nullable=True)

    # pending, generating, patch_validated, patch_applied, testing, passed, failed, rejected, error
    status = Column(String, default="pending", nullable=False)
    error_message = Column(Text, nullable=True)

    created_at = Column(DateTime(timezone=True), server_default=func.now())
    completed_at = Column(DateTime(timezone=True), nullable=True)
